//! Audit engine orchestrator executing collectors, evaluating rules, and synthesizing findings.

use std::time::Instant;

use openaudit_core::{
    Asset, AssetId, AssetType, Evidence, EvidencePayload, Finding, OrganizationId, ScanSummary,
};
use serde::{Deserialize, Serialize};

use crate::collector::firewall::FirewallInfo;
use crate::collector::os::OsInfo;
use crate::collector::permissions::FilePermissionInfo;
use crate::collector::ports::ListeningPort;
use crate::collector::ssh::SshConfig;
use crate::collector::users::UsersInfo;
use crate::collector::{
    CommandRunner, FileSystem, HostInspectionContext, PrivilegeLevel, RealCommandRunner,
    RealFileSystem,
};
use crate::error::EngineError;
use crate::rule::builtin::default_linux_rules;
use crate::rule::Rule;

/// An individual finding paired with its sanitized, size-bounded evidence record.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AuditFindingItem {
    /// Inspected target resource or configuration setting.
    pub target: String,
    /// The core security finding.
    pub finding: Finding,
    /// Supporting sanitized technical evidence.
    pub evidence: Evidence,
}

/// Comprehensive report generated by a host security audit execution.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AuditReport {
    /// Inspected host asset metadata.
    pub asset: Asset,
    /// Operating system identification.
    pub os_info: Option<OsInfo>,
    /// Execution privilege level of the audit process.
    pub current_privilege: PrivilegeLevel,
    /// Detected security findings.
    pub findings: Vec<AuditFindingItem>,
    /// Statistical aggregation of findings by severity.
    pub summary: ScanSummary,
    /// Execution duration in milliseconds.
    pub duration_ms: u64,
}

/// Audit execution engine coordinating telemetry collection and rule evaluation.
pub struct AuditEngine<FS = RealFileSystem, CR = RealCommandRunner> {
    fs: FS,
    runner: CR,
    rules: Vec<Box<dyn Rule>>,
}

impl<FS: std::fmt::Debug, CR: std::fmt::Debug> std::fmt::Debug for AuditEngine<FS, CR> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("AuditEngine")
            .field("fs", &self.fs)
            .field("runner", &self.runner)
            .field("rules_count", &self.rules.len())
            .finish()
    }
}

impl Default for AuditEngine<RealFileSystem, RealCommandRunner> {
    fn default() -> Self {
        Self {
            fs: RealFileSystem,
            runner: RealCommandRunner,
            rules: default_linux_rules(),
        }
    }
}

impl<FS: FileSystem, CR: CommandRunner> AuditEngine<FS, CR> {
    /// Creates a new `AuditEngine` with custom filesystem and command runner providers.
    #[must_use]
    pub fn new(fs: FS, runner: CR, rules: Vec<Box<dyn Rule>>) -> Self {
        Self { fs, runner, rules }
    }

    /// Executes a full, read-only local host security posture audit.
    ///
    /// # Errors
    /// Returns an [`EngineError`] if asset initialization or core domain validation fails.
    pub fn run_local_audit(&self, org_id: OrganizationId) -> Result<AuditReport, EngineError> {
        let start_time = Instant::now();

        // 1. Collect telemetry
        let os_info = OsInfo::collect(&self.fs).ok();
        let ssh_config = SshConfig::collect(&self.fs).ok();
        let users_info = UsersInfo::collect(&self.fs).ok();
        let listening_ports = ListeningPort::collect(&self.fs).unwrap_or_default();
        let firewall_info = Some(FirewallInfo::collect(&self.runner));
        let file_permissions = FilePermissionInfo::collect_critical(&self.fs).unwrap_or_default();
        let current_privilege = PrivilegeLevel::current();

        let context = HostInspectionContext {
            os: os_info.clone(),
            ssh: ssh_config,
            users: users_info,
            listening_ports,
            firewall: firewall_info,
            file_permissions,
            current_privilege,
        };

        // 2. Synthesize Asset representation
        let host_name = os_info
            .as_ref()
            .map_or("localhost", |os| os.pretty_name.as_str());

        let asset_seed = os_info
            .as_ref()
            .and_then(|os| os.machine_id.as_deref())
            .map_or_else(
                || format!("{org_id}:{host_name}"),
                |mid| format!("{org_id}:{mid}"),
            );

        let asset_id = AssetId::from_seed(asset_seed.as_bytes());
        let asset = Asset::with_id(
            asset_id,
            org_id,
            host_name,
            AssetType::LinuxHost,
            "127.0.0.1",
        )?;

        // 3. Evaluate rules
        let mut finding_items = Vec::new();
        let mut summary = ScanSummary::default();

        for rule in &self.rules {
            if rule.required_privilege() > current_privilege {
                continue;
            }

            for rule_finding in rule.evaluate(&context) {
                let finding = Finding::new(
                    org_id,
                    asset.id,
                    rule_finding.rule_id,
                    &rule_finding.target,
                    rule_finding.title,
                    rule_finding.description,
                    rule_finding.remediation,
                    rule_finding.severity,
                )?;

                let payload = EvidencePayload::from_text(&rule_finding.evidence_text)?;
                let evidence = Evidence::new(finding.id, rule_finding.evidence_type, payload);

                summary.record(finding.severity);
                finding_items.push(AuditFindingItem {
                    target: rule_finding.target,
                    finding,
                    evidence,
                });
            }
        }

        #[allow(clippy::cast_possible_truncation)]
        let duration_ms = start_time.elapsed().as_millis() as u64;

        Ok(AuditReport {
            asset,
            os_info,
            current_privilege,
            findings: finding_items,
            summary,
            duration_ms,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    struct MockAuditFs;
    impl FileSystem for MockAuditFs {
        fn read_to_string(&self, path: &str) -> Result<String, EngineError> {
            match path {
                "/etc/os-release" => Ok("ID=ubuntu\nPRETTY_NAME=\"Ubuntu 24.04\"\n".into()),
                "/etc/ssh/sshd_config" => Ok("PermitRootLogin yes\n".into()),
                "/etc/passwd" => Ok("root:x:0:0::/root:/bin/bash\n".into()),
                _ => Err(EngineError::Io(std::io::Error::new(
                    std::io::ErrorKind::NotFound,
                    "not found",
                ))),
            }
        }

        fn exists(&self, path: &str) -> bool {
            path == "/etc/os-release" || path == "/etc/ssh/sshd_config" || path == "/etc/passwd"
        }

        fn file_mode(&self, _path: &str) -> Result<u32, EngineError> {
            Ok(0o644)
        }

        fn read_dir(&self, _path: &str) -> Result<Vec<String>, EngineError> {
            Ok(Vec::new())
        }

        fn read_link(&self, _path: &str) -> Result<String, EngineError> {
            Err(EngineError::Io(std::io::Error::new(
                std::io::ErrorKind::NotFound,
                "not found",
            )))
        }
    }

    struct MockAuditRunner;
    impl CommandRunner for MockAuditRunner {
        fn run(&self, _program: &str, _args: &[&str]) -> Result<String, EngineError> {
            Ok("Status: active\n".into())
        }
    }

    #[test]
    fn test_audit_engine_execution_lifecycle() {
        let org_id = OrganizationId::new();
        let engine = AuditEngine::new(MockAuditFs, MockAuditRunner, default_linux_rules());

        let report = engine
            .run_local_audit(org_id)
            .expect("audit execution should succeed");

        assert_eq!(report.asset.organization_id, org_id);
        assert_eq!(report.asset.name, "Ubuntu 24.04");
        assert!(report.summary.high >= 1); // SSH root login rule triggered
        assert_eq!(
            usize::try_from(report.summary.total()).unwrap_or(0),
            report.findings.len()
        );

        // Invariant: each finding has an attached, redacted evidence item
        for item in &report.findings {
            assert!(item.evidence.is_redacted);
            assert_eq!(item.finding.id, item.evidence.finding_id);
        }
    }

    #[test]
    fn test_audit_engine_deterministic_asset_id() {
        let org_id = OrganizationId::new();
        let engine = AuditEngine::new(MockAuditFs, MockAuditRunner, default_linux_rules());

        let report1 = engine
            .run_local_audit(org_id)
            .expect("first run should succeed");
        let report2 = engine
            .run_local_audit(org_id)
            .expect("second run should succeed");

        assert_eq!(
            report1.asset.id, report2.asset.id,
            "AssetId must be deterministic across runs against the same host"
        );
    }
}
